
    create sequence project_seq start with 1 increment by 50;

    create table availability (
        start_hour integer not null,
        id bigint generated by default as identity,
        username varchar(255) not null,
        day_of_week enum ('FRIDAY','MONDAY','SATURDAY','SUNDAY','THURSDAY','TUESDAY','WEDNESDAY') not null,
        primary key (id)
    );

    create table project (
        required_students integer not null check ((required_students<=10) and (required_students>=1)),
        created_at timestamp(6),
        id bigint not null,
        title varchar(150) not null,
        description varchar(2000) not null,
        status enum ('ACTIVE','ARCHIVED','DELETED'),
        primary key (id)
    );

    create table project_program_restrictions (
        project_id bigint not null,
        program_restrictions enum ('BIOMEDICAL_ELECTRICAL_ENGINEERING','COMMUNICATIONS_ENGINEERING','COMPUTER_SYSTEMS_ENGINEERING','ELECTRICAL_ENGINEERING','SOFTWARE_ENGINEERING'),
        unique (project_id, program_restrictions)
    );

    create table project_topics (
        required_students integer not null check ((required_students>=1)),
        id bigint generated by default as identity,
        description varchar(2000) not null,
        program_restrictions varchar(255) not null,
        title varchar(255) not null,
        status enum ('ACTIVE','ARCHIVED','DELETED') not null,
        primary key (id)
    );

    create table students (
        assigned boolean not null,
        id bigint generated by default as identity,
        email varchar(255),
        name varchar(255),
        student_number varchar(255),
        primary key (id)
    );

